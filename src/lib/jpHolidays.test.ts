import { describe, expect, it } from 'vitest';
import { holidayName, holidaysOf } from './jpHolidays';

// 内閣府「国民の祝日について」の一覧と照合
const OFFICIAL: Record<number, string[]> = {
  2025: ['01-01', '01-13', '02-11', '02-23', '02-24', '03-20', '04-29', '05-03', '05-04', '05-05', '05-06',
    '07-21', '08-11', '09-15', '09-23', '10-13', '11-03', '11-23', '11-24'],
  2026: ['01-01', '01-12', '02-11', '02-23', '03-20', '04-29', '05-03', '05-04', '05-05', '05-06',
    '07-20', '08-11', '09-21', '09-22', '09-23', '10-12', '11-03', '11-23'],
  2027: ['01-01', '01-11', '02-11', '02-23', '03-21', '03-22', '04-29', '05-03', '05-04', '05-05',
    '07-19', '08-11', '09-20', '09-23', '10-11', '11-03', '11-23'],
};

describe('jpHolidays', () => {
  for (const [y, days] of Object.entries(OFFICIAL)) {
    it(`${y}年の祝日が内閣府の一覧と一致する`, () => {
      expect([...holidaysOf(Number(y)).keys()].sort()).toEqual(days.map(d => `${y}-${d}`));
    });
  }

  it('振替休日・国民の休日の名前を返し、平日は null', () => {
    expect(holidayName('2026-05-06')).toBe('振替休日');
    expect(holidayName('2026-09-22')).toBe('国民の休日');
    expect(holidayName('2026-11-03')).toBe('文化の日');
    expect(holidayName('2026-10-28')).toBeNull();
  });
});
